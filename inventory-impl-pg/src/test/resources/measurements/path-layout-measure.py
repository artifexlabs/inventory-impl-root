"""
path-layout measurement — PLAN.md ongoing item 6, "the large-tree path-layout
measurement that decides the final index shape".

WHY THIS EXISTS
    inventory-impl-changeset's 005-data.yaml is a FRESH-INSTALL schema. While no
    database anyone cares about has run it, its index shape can still be edited in
    place; the moment one has, Liquibase pins the changeSet by checksum and any
    change becomes a migration over live rows. This script answers the open
    questions BEFORE that window shuts.

WHAT IT ANSWERS
    Q1  entriesOf() filters with `lower(path_text) LIKE '%needle%'` — a LEADING
        wildcard, which a btree CANNOT serve. idx_data_entries_item_path helps the
        item_id filter and the ORDER BY, but the substring match itself scans every
        row of that medium. Does that matter at real scale, and does it want a
        pg_trgm GIN index instead?
    Q2  Does the path_elements dictionary earn its keep? It bounds storage by
        interning repeated components (src, target, node_modules...). Measure the
        interning ratio and what the ids actually cost.
        NOTE while reading results: as of 2026-08-27 `path_ids` is WRITTEN by the
        insert and the rename UPDATE and READ BY NOTHING — even renamePath matches
        on `path_text LIKE`, not on the id array. So the dictionary is currently
        pure write cost with no read path. That may still be correct (it is the
        append-only substrate a rename rewrites), but weigh it knowingly.
    Q3  findByHash is an equality lookup on a btree. Expected fine; measured anyway
        so "fine" is a number.
    Q4  findMirrorsOf self-joins on (path_hash, hash) but only path_hash is indexed,
        so each candidate is heap-fetched to check `hash`. The first trial run made
        this the SLOWEST query of the five — slower than the substring scan this
        script was written to investigate. A composite (path_hash, hash) is the
        candidate; the script builds it and re-measures.

WHAT IT NEEDS
    Realistic PATHS at volume — depth distribution and component repetition. It does
    NOT need real file contents, real hashes, or real removable media: the hash
    columns are opaque bytes where only cardinality matters, and hashing a large tree
    is the expensive part of this while buying nothing for a LAYOUT question.
    Any big tree you already have works:  --walk /usr   or   find / -type f > paths.txt

USAGE
    ./path-layout-measure.py --walk /usr --dsn postgresql://user:pw@localhost/measure
    ./path-layout-measure.py --paths paths.txt --scales 100000,500000 --dsn ...
    ./path-layout-measure.py --walk ~ --docker          # starts its own throwaway pg

    uv handles the dependency; no venv, no pip. Falls back to plain python3 if
    psycopg is already importable.

SAFETY
    Creates and DROPS a schema named `pathmeasure` in the target database. It never
    touches the public schema, so pointing it at a real inventory database is
    harmless — but point it at a scratch one anyway.
"""

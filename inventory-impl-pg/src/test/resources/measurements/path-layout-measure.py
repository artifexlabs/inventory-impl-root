# ---------------------------------------------------------------------------
# DDL — a faithful copy of inventory-impl-changeset 005-data.yaml (+ the minimal
# `items` it references). Kept literal rather than driven through Liquibase so the
# script stays a single scp-able file. If 005-data.yaml changes, change this too.
